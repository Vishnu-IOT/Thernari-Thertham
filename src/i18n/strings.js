/* Deep merge: values in `over` replace the base, nested blocks merge. */
const merge = (base, over = {}) => {
  const out = { ...base };
  for (const [k, v] of Object.entries(over)) {
    out[k] =
      v && typeof v === "object" && !Array.isArray(v) && base?.[k] && typeof base[k] === "object"
        ? merge(base[k], v)
        : v;
  }
  return out;
};

